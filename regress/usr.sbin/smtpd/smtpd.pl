use strict;
use warnings;
use Socket;

use Client;
use Smtpd;
use Server;
require 'funcs.pl';

sub usage {
	die "usage: smtpd.pl [test-args.pl]\n";
}

my $testfile;
our %args;
if (@ARGV and -f $ARGV[-1]) {
	$testfile = pop;
	do $testfile
	    or die "Do test file $testfile failed: ", $@ || $!;
}
@ARGV == 0 or usage();

# Allocate two ports up front: one for smtpd to listen on (SMTP client
# connects here), one for the LMTP sink to listen on (smtpd delivers here).
my ($smtp_port, $lmtp_port) = find_ports(num => 2);

my ($c, $d, $s);

# LMTP sink must be bound before smtpd reads its config.
$s = Server->new(
    forward      => "smtp",
    func         => \&lmtp_server,
    listendomain => AF_INET,
    listenaddr   => "127.0.0.1",
    listenport   => $lmtp_port,
    %{$args{server} || {}},
    testfile     => $testfile,
) unless ($args{server} || {})->{noserver};

# smtpd under test; the config is generated by Smtpd.pm from args{smtpd}{config}.
$d = Smtpd->new(
    listenaddr   => "127.0.0.1",
    listenport   => $smtp_port,
    connectaddr  => "127.0.0.1",
    connectport  => $lmtp_port,
    %{$args{smtpd} || {}},
    testfile     => $testfile,
);

# SMTP client that connects to smtpd's listen port.
$c = Client->new(
    forward       => "smtp",
    func          => \&smtp_client,
    connectdomain => AF_INET,
    connectaddr   => "127.0.0.1",
    connectport   => $smtp_port,
    %{$args{client} || {}},
    testfile      => $testfile,
    server        => \$s,
) unless ($args{client} || {})->{noclient};

# Start LMTP sink first so smtpd can connect at delivery time.
$s->run unless ($args{server} || {})->{noserver};

# Start smtpd and wait for it to announce itself ready.
$d->run;
$d->up;

# Start SMTP client and wait for it to report "Connected".
$c->run->up unless ($args{client} || {})->{noclient};

# Wait for LMTP sink to accept a connection (delivery).
$s->up unless ($args{server} || {})->{noserver};

# Wait for client and LMTP sink to finish their conversations.
$c->down unless ($args{client} || {})->{noclient};
$s->down unless ($args{server} || {})->{noserver};


# Shut smtpd down cleanly.
$d->kill_child;
$d->down;

check_logs($c, $d, $s, %args);
